"use client";

import { useEffect, useState, useTransition, type ReactNode } from "react";
import { generatePlayerAiInsightAction, loadPlayerAiInsightAction, type PlayerAiInsightState } from "./actions";

const SECTION_LABELS = ["Strengths:", "Holding you back:", "Hidden pattern:", "Practice plan:"];

/** Renders the insight with its labelled sections picked out. */
function InsightText({ text }: { text: string }) {
  return (
    <div className="space-y-2 text-sm leading-relaxed text-slate-800">
      {text
        .split(/\n+/)
        .filter((line) => line.trim())
        .map((line, i) => {
          const label = SECTION_LABELS.find((l) => line.startsWith(l));
          return label ? (
            <p key={i}>
              <span className="font-semibold text-emerald-800">{label}</span>
              {line.slice(label.length)}
            </p>
          ) : (
            <p key={i}>{line}</p>
          );
        })}
    </div>
  );
}

export function PlayerAiInsight({ playerId, seasonId, playerName }: { playerId: string; seasonId: string; playerName: string }) {
  const [state, setState] = useState<PlayerAiInsightState | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [pending, startTransition] = useTransition();

  useEffect(() => {
    let live = true;
    loadPlayerAiInsightAction(playerId, seasonId)
      .then((s) => live && setState(s))
      .catch(() => live && setError("Couldn't load the AI insight."));
    return () => {
      live = false;
    };
  }, [playerId, seasonId]);

  const generate = () => {
    setError(null);
    startTransition(async () => {
      const res = await generatePlayerAiInsightAction(playerId, seasonId);
      if (res.ok) {
        setState((s) => s && { ...s, summary: res.summary, at: res.at, legsCovered: res.legs, legsNow: res.legs });
      } else if (res.reason === "no_data") {
        setError("No completed legs to analyse yet this season.");
      } else {
        setError(res.message || "Couldn't generate the insight right now.");
      }
    });
  };

  if (!seasonId) return null;

  const shell = (children: ReactNode) => (
    <div className="rounded-xl border border-amber-200 bg-amber-50/40 p-3">
      <p className="mb-2 text-[11px] font-semibold uppercase tracking-wide text-amber-700">✨ AI player insights</p>
      {children}
    </div>
  );

  if (!state) return shell(<p className="text-xs text-slate-500">{error ?? "Checking for an insight…"}</p>);

  if (!state.configured && !state.summary) {
    return shell(
      <p className="text-xs text-slate-500">
        AI player insights appear once an Anthropic API key is configured on the server
        (<code className="text-slate-600">ANTHROPIC_API_KEY</code>).
      </p>
    );
  }

  if (state.legsNow === 0 && !state.summary) {
    return shell(<p className="text-xs text-slate-500">Insights unlock once {playerName} has completed a leg this season.</p>);
  }

  const newLegs = state.summary && state.legsCovered !== null ? state.legsNow - state.legsCovered : 0;

  return shell(
    <div className="fade-up">
      {state.summary ? (
        <InsightText text={state.summary} />
      ) : (
        <p className="text-sm text-slate-600">
          A coach&apos;s deep-dive into {playerName}&apos;s season — every visit studied for strengths, what&apos;s costing
          legs, hidden patterns (throwing first, deciders, finishing ranges) and a practice plan.
        </p>
      )}

      {pending && (
        <p className="mt-3 text-sm text-slate-500">
          Studying every visit of {playerName}&apos;s season… this can take up to a minute.
        </p>
      )}
      {error && <p className="mt-2 text-sm text-red-600">{error}</p>}

      {!pending && state.configured && (!state.summary || newLegs !== 0) && (
        <button type="button" className="btn-primary mt-3 text-sm" onClick={generate}>
          {state.summary
            ? `✨ Refresh — ${Math.abs(newLegs)} leg${Math.abs(newLegs) === 1 ? "" : "s"} ${newLegs > 0 ? "played" : "changed"} since`
            : "✨ Generate AI insights"}
        </button>
      )}

      {state.summary && !pending && (
        <p className="mt-3 text-[11px] text-slate-500">
          Generated by Claude · {state.legsCovered} leg{state.legsCovered === 1 ? "" : "s"} analysed
          {state.at ? ` · ${new Date(state.at).toLocaleDateString()}` : ""} · always double-check the numbers
        </p>
      )}
    </div>
  );
}
